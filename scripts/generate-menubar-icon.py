#!/usr/bin/env python3
"""Embed the traced tart SVG paths for native, resolution-independent rendering."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design/pastel-menubar.svg"
OUTPUT = ROOT / "Sources/PasteIt/UI/MenuBar/MenuBarTartArtwork.swift"
NS = {"s": "http://www.w3.org/2000/svg"}
TOKEN = re.compile(r"[MLCQZ]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?")
COUNTS = {"M": 2, "L": 2, "C": 6, "Q": 4, "Z": 0}


def commands(data):
    if TOKEN.sub("", data).strip(" ,\t\r\n"):
        raise ValueError("Unsupported SVG path command")
    tokens = TOKEN.findall(data)
    result, index, command = [], 0, None
    while index < len(tokens):
        if tokens[index] in COUNTS:
            command = tokens[index]
            index += 1
        if command is None:
            raise ValueError("Missing SVG command")
        count = COUNTS[command]
        values = tokens[index:index + count]
        if len(values) != count or any(value in COUNTS for value in values):
            raise ValueError("Incomplete SVG command")
        result.append((command, values))
        index += count
        command = "L" if command == "M" else command
        if command == "Z":
            command = None
    return result


def swift_path(name, path_commands):
    lines = [f"    static func {name}() -> CGPath {{", "        let path = CGMutablePath()"]
    for command, values in path_commands:
        points = [f"CGPoint(x: {values[i]}, y: {values[i+1]})" for i in range(0, len(values), 2)]
        if command == "M": lines.append(f"        path.move(to: {points[0]})")
        elif command == "L": lines.append(f"        path.addLine(to: {points[0]})")
        elif command == "Q": lines.append(f"        path.addQuadCurve(to: {points[1]}, control: {points[0]})")
        elif command == "C": lines.append(f"        path.addCurve(to: {points[2]}, control1: {points[0]}, control2: {points[1]})")
        elif command == "Z": lines.append("        path.closeSubpath()")
    return "\n".join([*lines, "        return path", "    }"])


def main():
    svg = ET.parse(SOURCE).getroot()
    if svg.get("viewBox") != "0 0 1024 1024":
        raise ValueError("Expected the traced 1024 × 1024 SVG coordinate system")
    path_commands = []
    for path in svg.findall("s:path", NS):
        transform = path.get("transform", "translate(0,0)")
        match = re.fullmatch(r"translate\(([-\d.]+)[ ,]+([-\d.]+)\)", transform)
        if not match:
            raise ValueError("Unsupported SVG transform")
        tx, ty = map(float, match.groups())
        for command, values in commands(path.attrib["d"]):
            adjusted = [f"{(float(value) + (tx if i % 2 == 0 else ty)) * 24 / 1024:.5f}"
                        for i, value in enumerate(values)]
            path_commands.append((command, adjusted))
    source = "// Generated by scripts/generate-menubar-icon.py from design/pastel-menubar.svg.\n"
    source += "// Regenerate after editing the SVG; do not edit these coordinates by hand.\nimport CoreGraphics\n\nenum MenuBarTartArtwork {\n"
    source += swift_path("outline", path_commands)
    OUTPUT.write_text(source + "\n}\n")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
