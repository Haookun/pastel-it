#!/usr/bin/env python3
"""Generate an immutable, data-only recovery pack and its compiled trust manifest."""
import argparse
import hashlib
import json
import plistlib
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ('en', 'zh-Hans', 'zh-Hant', 'ja', 'ko', 'de', 'es', 'fr', 'pl')


def outputs():
    catalog = json.loads((ROOT / 'Resources/Localization/Localizable.xcstrings').read_text())['strings']
    localizations = {language: {} for language in LANGUAGES}
    for key, entry in catalog.items():
        for language in LANGUAGES:
            localizations[language][key] = entry['localizations'].get(language, entry['localizations']['en'])['stringUnit']['value']
    info = plistlib.loads((ROOT / 'Info.plist').read_bytes())
    payload = {'schemaVersion': 1, 'applicationIdentifier': 'io.github.haookun.pastel-it',
               'appVersion': info['CFBundleShortVersionString'], 'appBuild': info['CFBundleVersion'],
               'localizations': localizations}
    data = (json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + '\n').encode()
    fingerprint = hashlib.sha256(data).hexdigest()
    digests = {}
    for language, translations in localizations.items():
        canonical = ''.join(f'{len(key.encode())}:{key}{len(value.encode())}:{value}' for key, value in sorted(translations.items())).encode()
        digests[language] = hashlib.sha256(canonical).hexdigest()
    relative = f'Resources/LanguagePacks/{fingerprint}.json'
    source = '// Generated by scripts/generate-language-pack.py; do not edit.\n'
    source += 'public enum LanguagePackManifest {\n'
    for key, value in [('sha256', fingerprint), ('appVersion', payload['appVersion']), ('appBuild', payload['appBuild']), ('relativePath', relative)]:
        source += f'    public static let {key} = {json.dumps(value)}\n'
    source += '    public static let translationDigests: [String: String] = [\n'
    for language, digest in sorted(digests.items()):
        source += f'        "{language}": "{digest}",\n'
    source += '    ]\n}\n'
    return {ROOT / relative: data, ROOT / 'Sources/PasteItCore/LanguagePackManifest.swift': source.encode()}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--validate-bundle', type=Path)
    args = parser.parse_args()
    generated = outputs()
    if args.validate_bundle:
        source = json.loads(next(data for path, data in generated.items() if path.suffix == '.json'))
        bundle = args.validate_bundle
        resources = bundle / 'Contents/Resources' if (bundle / 'Contents/Resources').is_dir() else bundle
        for language, expected in source['localizations'].items():
            file = resources / (language + '.lproj') / 'Localizable.strings'
            if not file.is_file():
                raise SystemExit(f'Missing packaged language: {language}')
            actual = plistlib.loads(subprocess.check_output(['plutil', '-convert', 'xml1', '-o', '-', str(file)]))
            if actual != expected:
                raise SystemExit(f'Incomplete/stale packaged language: {language}')
        print('All nine packaged language resources match this build.')
    for path, data in generated.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(f'Language recovery pack is stale/missing: {path.relative_to(ROOT)}. Run python3 scripts/generate-language-pack.py')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print('Language recovery pack and compiled integrity manifest verified.' if args.check else 'Language recovery pack and compiled integrity manifest generated.')


if __name__ == '__main__':
    main()
